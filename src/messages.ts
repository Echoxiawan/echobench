export function normalizeLocale(value: string | null | undefined): Locale | null {
  const normalized = value?.trim().toLowerCase();
  if (!normalized) return null;
  if (normalized.startsWith('zh')) return 'zh-CN';
  if (normalized.startsWith('en')) return 'en-US';
  return null;
}

export function systemLocale(): Locale {
  if (typeof navigator !== 'undefined') return normalizeLocale(navigator.language) ?? 'zh-CN';
  return 'zh-CN';
}

export function translate(locale: Locale, source: string, params?: Record<string, string | number>): string {
  const template = locale === 'en-US' ? enUS[source] ?? source : source;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

export function hasEnglishTranslation(source: string): boolean {
  return Object.hasOwn(enUS, source);
}

export function errorText(locale: Locale, cause: unknown): string {
  const raw = cause instanceof Error ? cause.message : String(cause);
  if (locale === 'zh-CN') return raw;
  const exact = enUS[raw];
  if (exact) return exact;
  if (/device unauthorized/i.test(raw)) return translate(locale, '设备尚未授权 USB 调试，EchoBench 无法建立连接。');
  if (/\boffline\b/i.test(raw)) return translate(locale, '设备当前处于离线状态。');
  if (/ANDROID_HOME|ANDROID_SDK_ROOT|Android SDK/i.test(raw)) return translate(locale, 'Android SDK 未安装、路径无效或环境变量未配置。');
  if (/ECONNREFUSED|4723|Appium.*not running/i.test(raw)) return translate(locale, 'Appium 服务未能启动或无法连接。');
  if (/requires a development team|xcodebuild failed with code 65/i.test(raw)) return translate(locale, 'iOS WebDriverAgent 签名失败。');
  if (/RemoteXPC tunnel|Tunnel registry port not found/i.test(raw)) return translate(locale, 'iOS 18+ 真机 RemoteXPC 隧道创建失败。');
  return 'The operation failed. Open the runtime logs for technical details.';
}

/** 本地化历史草稿和录制阶段生成的步骤描述。 */
export function localizeGeneratedText(locale: Locale, source: string): string {
  if (locale === 'zh-CN' || !source) return source;
  const exact = enUS[source];
  if (exact) return exact;
  let match = source.match(/^输入「(.*)」$/);
  if (match) return `Enter "${match[1]}"`;
  match = source.match(/^点击「(.*)」$/);
  if (match) return `Tap "${match[1]}"`;
  match = source.match(/^坐标点击「(.*)」 \((.*), (.*)\)$/);
  if (match) return `Tap coordinates "${match[1]}" (${match[2]}, ${match[3]})`;
  match = source.match(/^双击「(.*)」$/);
  if (match) return `Double tap "${match[1]}"`;
  match = source.match(/^长按「(.*)」$/);
  if (match) return `Long press "${match[1]}"`;
  match = source.match(/^双指放大「(.*)」$/);
  if (match) return `Pinch out "${match[1]}"`;
  match = source.match(/^双指缩小「(.*)」$/);
  if (match) return `Pinch in "${match[1]}"`;
  match = source.match(/^([上下左右])滑 (\d+)px$/);
  if (match) return `Swipe ${translate(locale, match[1])} ${match[2]}px`;
  match = source.match(/^(.+)：(.+?)(?:（(.+)）)?$/);
  if (match) return `${translate(locale, match[1])}: ${match[2]}${match[3] ? ` (${match[3]})` : ''}`;
  return translate(locale, source);
}
